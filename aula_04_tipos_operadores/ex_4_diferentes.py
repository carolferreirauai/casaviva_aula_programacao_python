# Exercício 4:
# Depois que o usuário informar dois números, compare se eles são
# diferentes e apresente o resultado na saída.

# entrada de dados
numero1 = int(input("Digite um número: "))
numero2 = int(input("Digite outro número: "))

# verificar a diferenças
diferenca = numero1 != numero2

# saída de dados
print (diferenca)