# Exercício 5:
# Crie um código que peça ao usuário dois números e, em seguida, calcule
# a soma, a subtração, a multiplicação e a divisão entre eles, exibindo
# todos os resultados na saída

# entrada de dados
numero1 = int(input("Digite um número: "))
numero2 = int(input("Digite outro número: "))

# calcule
# soma
soma = numero1 + numero2

# subtração
subtracao = numero1 - numero2

# multiplicação
multiplicacao = numero1 * numero2

# divisão 
divisao = numero1 / numero2

# saída de dados
print("Soma: ", soma)
print("Subtração: ", subtracao)
print("Multiplicação: ", multiplicacao)
print("Divisão: ", divisao)
