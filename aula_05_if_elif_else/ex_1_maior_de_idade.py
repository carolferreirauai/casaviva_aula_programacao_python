# Exercício 1:
# Faça um programa que permita o usuário inserir sua idade e depois
# verifique se o mesmo é maior (idade > 18) ou menor (idade < 18) de
# idade.

# entrada de dados
idade = int(input("Digite uma idade: "))

# verificar idade menor ou maior de idade e 
# saída de dados
if idade > 18:
    print("Você é maior de idade!")
else:
    print("Você é menor de idade!")
